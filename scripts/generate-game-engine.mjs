// Keep the server generator exactly aligned with the authored TypeScript source.
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../src/core/juego-clase.ts', import.meta.url), 'utf8');
const output = '// Generated by scripts/generate-game-engine.mjs. Do not edit.\n' + ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022, removeComments: true } }).outputText;
const target = new URL('../api/src/lib/juegos-generador.js', import.meta.url);
if (process.argv.includes('--check')) { if (fs.readFileSync(target, 'utf8').replaceAll('\r\n','\n') !== output.replaceAll('\r\n','\n')) throw Error('Regenerate the game engine'); }
else fs.writeFileSync(target, output);
